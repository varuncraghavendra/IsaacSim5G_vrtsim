#!/usr/bin/env python3
"""
/plotter publisher for IsaacSim5G.

Subscribes to the robot's odometry topic (default `/chassis/odom`) and
the simulator clock (`/clock`, present when Isaac is publishing sim time)
and republishes a time-aligned PlotterSample at ~30 Hz on `/plotter`.

Fields:
    sim_time   builtin_interfaces/Time   — last seen sim time (from /clock,
                                            or the odom header stamp if /clock
                                            is unavailable)
    rtf        float64                   — rolling slope d(sim_time)/d(wall_time)
                                            over the last N samples; 1.0 = realtime
    x, y, z    float64                   — robot pose (odom frame)
    vx, vy, vz float64                   — body-frame linear velocity from odom.twist
    heading    float64                   — yaw (rad) from odom.pose.orientation

Usage:
    ros2 run … or directly:

        ./teleop_app/.venv/bin/python isaac/plotter_publisher.py \\
            --odom-topic /chassis/odom \\
            --publish-rate-hz 30

Runs in the default network namespace (Isaac's). The /plotter topic is a
*pre-radio* readout — it shows Isaac's own state, not what the operator
dashboard receives after the 5G uplink. To plot post-radio data, subscribe
on the operator side to the bridge's existing uplink JSON envelope.
"""
from __future__ import annotations

import argparse
import collections
import math
import sys
import time

import rclpy
from nav_msgs.msg import Odometry
from rclpy.node import Node
from rclpy.qos import HistoryPolicy, QoSProfile, ReliabilityPolicy
from rosgraph_msgs.msg import Clock

try:
    # Generated by the colcon-built workspace; only importable after
    # `source ros2_ws/install/setup.bash`.
    from network_aware_msgs.msg import PlotterSample
except ImportError as exc:
    print("[plotter] cannot import network_aware_msgs.msg.PlotterSample.\n"
          "          Did you forget to source ros2_ws/install/setup.bash?\n"
          f"          (underlying error: {exc})", file=sys.stderr)
    raise


def yaw_from_quaternion(qx: float, qy: float, qz: float, qw: float) -> float:
    """ZYX yaw from a unit quaternion. Same convention as ue_teleop_bridge."""
    siny_cosp = 2.0 * (qw * qz + qx * qy)
    cosy_cosp = 1.0 - 2.0 * (qy * qy + qz * qz)
    return math.atan2(siny_cosp, cosy_cosp)


class PlotterPublisher(Node):
    def __init__(
        self,
        odom_topic: str,
        out_topic: str,
        publish_rate_hz: float,
        rtf_window: int,
    ):
        super().__init__("plotter_publisher")

        sensor_qos = QoSProfile(
            reliability=ReliabilityPolicy.BEST_EFFORT,
            history=HistoryPolicy.KEEP_LAST,
            depth=30,
        )

        self._pub = self.create_publisher(PlotterSample, out_topic, sensor_qos)
        self.create_subscription(Odometry, odom_topic, self._on_odom, sensor_qos)
        self.create_subscription(Clock, "/clock", self._on_clock, sensor_qos)

        # Latest cached values.
        self._latest_odom: Odometry | None = None
        # Rolling (sim_seconds, wall_seconds) pairs for RTF slope.
        self._clock_samples: collections.deque[tuple[float, float]] = \
            collections.deque(maxlen=max(2, rtf_window))
        self._last_sim_time_msg = None  # builtin_interfaces/Time of most recent /clock

        period = 1.0 / max(1.0, float(publish_rate_hz))
        self.create_timer(period, self._on_publish_tick)

        self.get_logger().info(
            f"plotter ready: odom={odom_topic} -> {out_topic} "
            f"@ {publish_rate_hz:.1f} Hz, rtf_window={rtf_window}")

    def _on_odom(self, msg: Odometry):
        self._latest_odom = msg

    def _on_clock(self, msg: Clock):
        sim_sec = float(msg.clock.sec) + float(msg.clock.nanosec) * 1e-9
        wall_sec = time.monotonic()
        self._clock_samples.append((sim_sec, wall_sec))
        self._last_sim_time_msg = msg.clock

    def _compute_rtf(self) -> float:
        """Slope of sim_time vs wall_time over the rolling window.

        Returns NaN if we have fewer than 2 samples or the wall span is
        zero. Otherwise (sim_last - sim_first) / (wall_last - wall_first).
        """
        if len(self._clock_samples) < 2:
            return float("nan")
        sim_first, wall_first = self._clock_samples[0]
        sim_last, wall_last = self._clock_samples[-1]
        dw = wall_last - wall_first
        if dw <= 0.0:
            return float("nan")
        return (sim_last - sim_first) / dw

    def _on_publish_tick(self):
        odom = self._latest_odom
        if odom is None:
            return

        out = PlotterSample()

        # sim_time: prefer /clock if Isaac is publishing it, otherwise fall
        # back to the odom header stamp (which is normally use_sim_time'd by
        # Isaac's ROS bridge anyway).
        if self._last_sim_time_msg is not None:
            out.sim_time = self._last_sim_time_msg
        else:
            out.sim_time = odom.header.stamp

        out.rtf = self._compute_rtf()

        p = odom.pose.pose.position
        o = odom.pose.pose.orientation
        t = odom.twist.twist
        out.x = float(p.x)
        out.y = float(p.y)
        out.z = float(p.z)
        out.vx = float(t.linear.x)
        out.vy = float(t.linear.y)
        out.vz = float(t.linear.z)
        out.heading = yaw_from_quaternion(
            float(o.x), float(o.y), float(o.z), float(o.w))

        self._pub.publish(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    ap.add_argument("--odom-topic", default="/chassis/odom",
                    help="Source odometry topic.")
    ap.add_argument("--out-topic", default="/plotter",
                    help="Output topic name.")
    ap.add_argument("--publish-rate-hz", type=float, default=30.0)
    ap.add_argument("--rtf-window", type=int, default=60,
                    help="Number of /clock samples used for the RTF slope.")
    args = ap.parse_args()

    rclpy.init()
    node = PlotterPublisher(
        odom_topic=args.odom_topic,
        out_topic=args.out_topic,
        publish_rate_hz=args.publish_rate_hz,
        rtf_window=args.rtf_window,
    )
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        try:
            rclpy.shutdown()
        except Exception:
            pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
